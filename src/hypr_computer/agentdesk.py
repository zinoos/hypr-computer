"""Agent desktops: a nested Hyprland per agent, with its own seat (cursor, keyboard focus), clipboard,
Xwayland and D-Bus session. It renders to a headless output, so it keeps working while nobody looks at it.
A window on the user's desktop mirrors it live (the viewer), so the user sees the agent's cursor and windows.
Closing the viewer stops the agent desktop.

    python -m hypr_computer.agentdesk keep NAME   # internal: watchdog that stops NAME when its viewer closes
"""

from __future__ import annotations

import json
import os
import signal
import subprocess
import sys
import time
from dataclasses import asdict, dataclass, field

from . import hypr
from .hypr import HyprError

RUN = os.path.join(os.environ.get("XDG_RUNTIME_DIR", f"/run/user/{os.getuid()}"), "hypr-computer")
STATE = os.path.expanduser("~/.local/share/hypr-computer/agents")
HEADLESS = "AGENT-1"

CONFIG = """\
-- Agent desktop {name} (generated by hypr-computer; edits are overwritten)
hl.env("XCURSOR_SIZE", "{cursor}")
hl.env("HYPRCURSOR_SIZE", "{cursor}")
{cursor_theme}
hl.config({{
    general = {{
        gaps_in = 4, gaps_out = 8, border_size = 3, layout = "dwindle",
        col = {{ active_border = "rgba({accent}ff)", inactive_border = "rgba(44444488)" }},
    }},
    decoration = {{ rounding = 8 }},
    animations = {{ enabled = true }},
    cursor = {{ no_hardware_cursors = true, inactive_timeout = 0 }},
    misc = {{ disable_hyprland_logo = true, disable_splash_rendering = true, background_color = "rgb({background})",
              disable_watchdog_warning = true }},
    input = {{ kb_layout = "{layout}", kb_variant = "{variant}", follow_mouse = 1 }},
}})
-- The agent's real screen is a headless output; viewer windows on the user's desktop mirror it.
hl.monitor({{ output = "{headless}", mode = "{width}x{height}@60", position = "0x0", scale = 1 }})
for i = 1, 4 do
    hl.monitor({{ output = "WAYLAND-" .. i, mode = "preferred", position = "auto", scale = 1, mirror = "{headless}" }})
end
"""

ACCENTS = ["ff8c1a", "33c3ff", "b26bff", "4cd964", "ff4f7b", "ffd60a"]


class AgentDeskError(RuntimeError):
    pass


@dataclass
class Desk:
    name: str
    pid: int  # nested Hyprland
    sig: str
    wl_socket: str
    dbus: str
    dbus_pid: int
    width: int
    height: int
    owner_pid: int
    state_dir: str
    run_dir: str
    host_sig: str
    host_wayland: str
    accent: str
    created: float
    place: int = 0  # canvas place / workspace number the viewer lives on (Super+N); 0 = none
    monitor: str = ""
    aux_pids: list = field(default_factory=list)  # AT-SPI launcher/registry on the private bus

    @property
    def env(self) -> dict:
        e = dict(os.environ)
        e.update(WAYLAND_DISPLAY=self.wl_socket, HYPRLAND_INSTANCE_SIGNATURE=self.sig,
                 DBUS_SESSION_BUS_ADDRESS=self.dbus, XDG_CURRENT_DESKTOP="Hyprland")
        e.pop("DISPLAY", None)
        return e

    def alive(self) -> bool:
        return _alive(self.pid)

    def save(self):
        os.makedirs(RUN, exist_ok=True)
        with open(os.path.join(RUN, f"{self.name}.json"), "w") as f:
            json.dump(asdict(self), f)


def _alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except OSError:
        return False
    try:
        with open(f"/proc/{pid}/stat") as f:
            return f.read().split()[2] != "Z"
    except OSError:
        return False


def list_desks() -> list[Desk]:
    out = []
    if not os.path.isdir(RUN):
        return out
    for fn in sorted(os.listdir(RUN)):
        if not fn.endswith(".json"):
            continue
        try:
            with open(os.path.join(RUN, fn)) as f:
                d = Desk(**json.load(f))
        except Exception:
            continue
        if d.alive():
            out.append(d)
        else:
            _cleanup_files(d)
    return out


def _cleanup_files(d: Desk):
    for p in (os.path.join(RUN, f"{d.name}.json"),):
        try:
            os.unlink(p)
        except OSError:
            pass
    if d.dbus_pid and _alive(d.dbus_pid):
        try:
            os.kill(d.dbus_pid, signal.SIGTERM)
        except OSError:
            pass


def _host_keyboard(host_sig: str) -> tuple[str, str]:
    try:
        kbs = hypr.query("devices", host_sig)["keyboards"]
        k = next((k for k in kbs if k.get("main")), kbs[0])
        return k["layout"].split(",")[0] or "us", (k.get("variant") or "").split(",")[0]
    except Exception:
        return "us", ""


def _host_cursor_theme() -> str:
    t = os.environ.get("XCURSOR_THEME") or os.environ.get("HYPRCURSOR_THEME")
    return f'hl.env("XCURSOR_THEME", "{t}")\nhl.env("HYPRCURSOR_THEME", "{t}")' if t else ""


AGENT_PLACES = list(range(4, 11))  # Super+4 … Super+0 (place 10); 1-3 belong to the user


def place_label(p: int) -> str:
    return "0" if p == 10 else str(p)


def start(name: str | None = None, width: int | None = None, height: int | None = None, viewer: str = "place",
          host_sig: str | None = None, host_wayland: str | None = None, place: int | None = None) -> tuple[Desk, str]:
    """Start (or adopt) an agent desktop. Returns (desk, note).
    viewer="place" puts its live view full-size on a free place 4…0 (or `place`), so Super+N shows it."""
    host_sig = host_sig or os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")
    host_wayland = host_wayland or os.environ.get("WAYLAND_DISPLAY", "wayland-1")
    existing = list_desks()
    if place is not None:
        place = 10 if place == 0 else place
        for d in existing:
            if d.place == place:
                d.owner_pid = os.getpid()
                d.save()
                return d, f"attached to the agent desktop on place {place_label(place)}"
        if place in (1, 2, 3):
            raise AgentDeskError("places 1-3 are the user's; agent desktops use 4-9 and 0")
    if name:
        for d in existing:
            if d.name == name:
                d.owner_pid = os.getpid()
                d.save()
                return d, f"attached to running agent desktop {name!r}"
    elif place is None:
        # Adopt a desktop whose MCP server is gone (e.g. after a restart) before creating a new one.
        for d in existing:
            if not _alive(d.owner_pid):
                d.owner_pid = os.getpid()
                d.save()
                return d, f"adopted running agent desktop {d.name!r}"
    idx = len(existing)
    area = None
    if viewer == "place":
        if place is None:
            used = {d.place for d in existing}
            place = next((p for p in AGENT_PLACES if p not in used), None)
            if place is None:
                raise AgentDeskError("all agent places (4-9, 0) are taken; stop one first")
        area = _place_area(place, host_sig)
        if area is None:
            # No Phantomat canvas: the viewer goes to plain workspace N at the focused monitor's size.
            mons = hypr.screens(hypr.query("monitors", host_sig))
            m = next((m for m in mons if m.get("focused")), mons[0])
            _, _, mw, mh = hypr.monitor_box(m)
            area = {"w": int(mw) - 40, "h": int(mh) - 80, "monitor": m["name"]}
    width = width or (int(area["w"]) if area else 1280)
    height = height or (int(area["h"]) if area else 800)
    if not name:
        taken = {d.name for d in existing}
        name = f"desktop-{place_label(place)}" if place else \
            next(f"agent-{i}" for i in range(1, 100) if f"agent-{i}" not in taken)
    accent = ACCENTS[idx % len(ACCENTS)]
    run_dir = os.path.join(RUN, name)
    state_dir = os.path.join(STATE, name)
    os.makedirs(run_dir, exist_ok=True)
    os.makedirs(state_dir, exist_ok=True)

    # Private session bus: single-instance apps (GApplication, D-Bus activated) start fresh here instead
    # of opening their window in the user's running instance.
    bus = f"unix:path={run_dir}/bus"
    try:
        os.unlink(f"{run_dir}/bus")
    except OSError:
        pass
    r = subprocess.run(["dbus-daemon", "--session", "--fork", "--nopidfile", f"--address={bus}", "--print-pid=1"],
                       capture_output=True, text=True, timeout=10)
    if r.returncode:
        raise AgentDeskError(f"dbus-daemon failed: {r.stderr.strip()}")
    dbus_pid = int(r.stdout.split()[0])
    # Accessibility on the private bus: D-Bus activation of the AT-SPI launcher fails there, so start it
    # (and its registry) directly; both exit when the bus goes away.
    aux = []
    for cmd in (["/usr/libexec/at-spi-bus-launcher", "--launch-immediately", "--a11y=1"],
                ["/usr/libexec/at-spi2-registryd"]):
        if os.path.exists(cmd[0]):
            aux.append(subprocess.Popen(cmd, env=dict(os.environ, DBUS_SESSION_BUS_ADDRESS=bus), start_new_session=True,
                             stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL).pid)
            time.sleep(0.3)

    layout, variant = _host_keyboard(host_sig)
    cfg = os.path.join(run_dir, "hyprland.lua")
    with open(cfg, "w") as f:
        f.write(CONFIG.format(name=name, cursor=32, cursor_theme=_host_cursor_theme(), accent=accent,
                              background="1b1d22", layout=layout, variant=variant, headless=HEADLESS,
                              width=width, height=height))

    before = {i["instance"] for i in _instances()}
    host_before = {c["address"] for c in hypr.query("clients", host_sig)}
    host_active = (hypr.query("activewindow", host_sig) or {}).get("address")
    env = dict(os.environ)
    for k in ("HYPRLAND_INSTANCE_SIGNATURE", "HYPRLAND_CMD", "DISPLAY", "XDG_SESSION_ID"):
        env.pop(k, None)
    env.update(WAYLAND_DISPLAY=host_wayland, DBUS_SESSION_BUS_ADDRESS=bus)
    log = open(os.path.join(run_dir, "hyprland.log"), "w")
    proc = subprocess.Popen(["Hyprland", "-c", cfg], env=env, stdout=log, stderr=subprocess.STDOUT,
                            stdin=subprocess.DEVNULL, start_new_session=True, cwd=state_dir)
    if place:
        # Host side (agent-places.lua): when this pid's window opens, it goes straight into its place,
        # without splitting the place the user is on or taking their focus.
        try:
            hypr.eval_lua(f"if AgentPlaces then AgentPlaces.claim({proc.pid}, {place}) end", host_sig)
        except HyprError:
            pass

    inst = None
    t0 = time.time()
    while time.time() - t0 < 15:
        if proc.poll() is not None:
            raise AgentDeskError(f"nested Hyprland exited ({proc.returncode}); see {run_dir}/hyprland.log")
        for i in _instances():
            if i["instance"] not in before and i["pid"] == proc.pid:
                inst = i
        if inst:
            try:
                hypr.query("monitors", inst["instance"])
                break
            except Exception:
                pass
        time.sleep(0.2)
    if not inst:
        proc.kill()
        raise AgentDeskError("nested Hyprland did not come up within 15 s")
    sig = inst["instance"]

    # The real screen: a headless output that renders even when the viewer is hidden.
    hypr.request(f"output create headless {HEADLESS}", inst=sig)
    time.sleep(0.3)
    hypr.request("reload", inst=sig)  # re-applies the monitor rules: the viewer output now mirrors

    d = Desk(name=name, pid=proc.pid, sig=sig, wl_socket=inst["wl_socket"], dbus=bus, dbus_pid=dbus_pid,
             width=width, height=height, owner_pid=os.getpid(), state_dir=state_dir, run_dir=run_dir,
             host_sig=host_sig, host_wayland=host_wayland, accent=accent, created=time.time(),
             place=place or 0, monitor=(area or {}).get("monitor", ""), aux_pids=aux)
    d.save()

    note = ""
    viewer_win = _wait_viewer(d, host_before)
    if viewer_win:
        time.sleep(0.5)
        place_viewer(d, viewer, index=idx)
        if not ensure_mirror(d):
            note = "the viewer is not mirroring the agent screen"
        now = (hypr.query("activewindow", host_sig) or {}).get("address")
        if host_active and now != host_active:
            try:
                hypr.dispatch(f'hl.dsp.focus({{window = "address:{host_active}"}})', host_sig)
            except HyprError:
                pass
    else:
        note = "viewer window did not appear on the host"
    try:
        hypr.eval_lua(f'hl.notification.create({{text = "{name}: agent desktop", timeout = 4000, color = "rgb({accent})"}})', sig)
    except HyprError:
        pass
    subprocess.Popen([sys.executable, "-m", "hypr_computer.agentdesk", "keep", name], start_new_session=True,
                     stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                     env=dict(os.environ, PYTHONPATH=os.pathsep.join(sys.path)))
    where = f", live on the user's place {place_label(place)} (Super+{place_label(place)})" if place else ""
    return d, f"started agent desktop {name!r} ({width}x{height}){where}" + (f"; {note}" if note else "")


def _place_area(place: int, host_sig: str) -> dict | None:
    try:
        return hypr.eval_lua(f"return AgentPlaces and AgentPlaces.area({place}) or nil", host_sig)
    except HyprError:
        return None


def ensure_mirror(d: Desk, timeout: float = 3.0) -> bool:
    """Monitor rules apply on the next reconfigure: if the viewer output isn't mirroring yet, wiggle the
    viewer window's size by a pixel on the host so the nested compositor reconfigures it."""
    def ok():
        mons = hypr.query("monitors all", d.sig)
        views = [m for m in mons if m["name"].startswith("WAYLAND-")]
        return bool(views) and all(str(m.get("mirrorOf", "none")) not in ("none", "") for m in views)
    t0 = time.time()
    while time.time() - t0 < timeout:
        if ok():
            return True
        w = viewer_window(d)
        if w:
            sel = f'"address:{w["address"]}"'
            sx, sy = w["size"]
            hypr.dispatch(f"hl.dsp.window.resize({{x = {sx - 1}, y = {sy}, relative = false, window = {sel}}})", d.host_sig)
            time.sleep(0.3)
            hypr.dispatch(f"hl.dsp.window.resize({{x = {sx}, y = {sy}, relative = false, window = {sel}}})", d.host_sig)
        time.sleep(0.4)
    return ok()


def _instances() -> list[dict]:
    try:
        return json.loads(subprocess.run(["hyprctl", "instances", "-j"], capture_output=True, text=True,
                                         timeout=5).stdout or "[]")
    except Exception:
        return []


def viewer_window(d: Desk) -> dict | None:
    try:
        return next((c for c in hypr.query("clients", d.host_sig) if c["pid"] == d.pid), None)
    except HyprError:
        return None


def _wait_viewer(d: Desk, host_before: set, timeout: float = 8) -> dict | None:
    t0 = time.time()
    while time.time() - t0 < timeout:
        w = viewer_window(d)
        if w and w["address"] not in host_before:
            return w
        time.sleep(0.15)
    return viewer_window(d)


def place_viewer(d: Desk, mode: str = "pip", scale: float = 0.5, corner: str = "bottom-right", index: int = 0) -> str:
    """pip: small, floating and pinned over everything (stays put while you move around the canvas).
    window: a normal floating window on the current canvas place. tile: leave it to the tiler.
    hidden: tucked away in the special workspace 'agents' (the agent keeps working)."""
    w = viewer_window(d)
    if w is None:
        _recreate_viewer(d)
        w = viewer_window(d)
        if w is None:
            raise AgentDeskError("no viewer window and could not create one")
    hs = d.host_sig
    sel = f'"address:{w["address"]}"'
    if mode == "place":
        if not d.place:
            raise AgentDeskError("this agent desktop has no place; start one with a place (4-9, 0)")
        if w["pinned"]:
            hypr.dispatch(f'hl.dsp.window.pin({{action = "disable", window = {sel}}})', hs)
        if w["workspace"]["name"].startswith("special"):
            ws = (hypr.query("activeworkspace", hs) or {}).get("name", "1")
            hypr.dispatch(f'hl.dsp.window.move({{workspace = {hypr.lua_str(ws)}, follow = false, window = {sel}}})', hs)
        a = hypr.eval_lua(f'return AgentPlaces and AgentPlaces.put("{w["address"]}", {d.place}) or nil', hs)
        if a is None:
            hypr.dispatch(f'hl.dsp.window.move({{workspace = "{d.place}", follow = false, window = {sel}}})', hs)
        return f"viewer fills place {place_label(d.place)} (Super+{place_label(d.place)} to watch)"
    if mode == "hidden":
        hypr.dispatch(f'hl.dsp.window.move({{workspace = "special:agents", follow = false, window = {sel}}})', hs)
        return "viewer hidden in special workspace 'agents' (toggle it like any special workspace)"
    if mode == "tile":
        if w["floating"]:
            hypr.dispatch(f'hl.dsp.window.float({{action = "disable", window = {sel}}})', hs)
        return "viewer tiled"
    vw, vh = int(d.width * scale), int(d.height * scale)
    if w["workspace"]["name"].startswith("special"):
        ws = (hypr.query("activeworkspace", hs) or {}).get("name", "1")
        hypr.dispatch(f'hl.dsp.window.move({{workspace = {hypr.lua_str(ws)}, follow = false, window = {sel}}})', hs)
    if not w["floating"]:
        hypr.dispatch(f'hl.dsp.window.float({{action = "enable", window = {sel}}})', hs)
    hypr.dispatch(f"hl.dsp.window.resize({{x = {vw}, y = {vh}, relative = false, window = {sel}}})", hs)
    mons = hypr.screens(hypr.query("monitors", hs))
    m = next((m for m in mons if m.get("focused")), mons[0])
    mx, my, mw, mh = hypr.monitor_box(m)
    margin = 24
    off = index * (vh + 12)
    x = mx + (margin if "left" in corner else mw - vw - margin)
    y = my + (margin + 40 + off if "top" in corner else mh - vh - margin - off)
    if mode == "pip":
        if not w["pinned"]:
            hypr.dispatch(f'hl.dsp.window.pin({{action = "enable", window = {sel}}})', hs)
        # Pinned windows on the Phantomat canvas are screen-fixed: layout coordinates.
        hypr.dispatch(f"hl.dsp.window.move({{x = {int(x)}, y = {int(y)}, window = {sel}}})", hs)
        return f"viewer is a {vw}x{vh} picture-in-picture at the {corner} of {m['name']}"
    if w["pinned"]:
        hypr.dispatch(f'hl.dsp.window.pin({{action = "disable", window = {sel}}})', hs)
    canvas = hypr.canvas_state(mons, hs)
    if canvas.active:
        x = canvas.view_x + (x - canvas.anchor_x) / canvas.zoom
        y = canvas.view_y + (y - canvas.anchor_y) / canvas.zoom
    hypr.dispatch(f"hl.dsp.window.move({{x = {int(x)}, y = {int(y)}, window = {sel}}})", hs)
    return f"viewer is a floating {vw}x{vh} window on the current place of {m['name']}"


def _recreate_viewer(d: Desk):
    host_before = {c["address"] for c in hypr.query("clients", d.host_sig)}
    hypr.request("output create wayland", inst=d.sig)
    time.sleep(0.5)
    _wait_viewer(d, host_before, 5)
    ensure_mirror(d)


def stop(d: Desk) -> str:
    try:
        hypr.dispatch("hl.dsp.exit()", d.sig)
    except Exception:
        pass
    t0 = time.time()
    while d.alive() and time.time() - t0 < 5:
        time.sleep(0.1)
    # Hyprland forks; everything it started shares its process group (start_new_session).
    for sig in (signal.SIGTERM, signal.SIGKILL):
        try:
            os.killpg(d.pid, sig)
        except OSError:
            break
        time.sleep(0.8)
    for pid in d.aux_pids:
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass
    _cleanup_files(d)
    return f"stopped agent desktop {d.name!r}"


def _keep(name: str):
    """Watchdog: once the viewer window has existed and then disappears (user closed it), stop the desk."""
    seen = False
    gone_since = None
    while True:
        time.sleep(1.5)
        d = next((x for x in list_desks() if x.name == name), None)
        if d is None:
            return
        w = viewer_window(d)
        if w:
            seen, gone_since = True, None
            continue
        if not seen:
            continue
        gone_since = gone_since or time.time()
        if time.time() - gone_since > 3:
            stop(d)
            return


if __name__ == "__main__":
    if len(sys.argv) == 3 and sys.argv[1] == "keep":
        _keep(sys.argv[2])
